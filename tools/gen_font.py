#!/usr/bin/env python3
"""Generate runtime/font8x16.h: an 8x16 bitmap font (ASCII + symbols) rendered from Liberation Mono
(SIL Open Font License 1.1). usage: gen_font.py LiberationMono-Regular.ttf > runtime/font8x16.h"""
import sys
from PIL import Image, ImageDraw, ImageFont
font = ImageFont.truetype(sys.argv[1], 14)
cps = list(range(32, 127)) + [ord(c) for c in '…◄►✓•']
print("// Generated by tools/gen_font.py from Liberation Mono (SIL OFL 1.1). 8x16 cells, 1 bit per pixel, MSB = left.")
print("#pragma once\n#include <stdint.h>")
print("#define FONT_COUNT %d" % len(cps))
print("static const uint16_t font_cps[FONT_COUNT] = {%s};" % ",".join(str(c) for c in cps))
print("static const uint8_t font8x16[FONT_COUNT][16] = {")
for cp in cps:
    im = Image.new('L', (8, 16), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 1), chr(cp), font=font, fill=255)
    rows = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) >= 110: b |= 0x80 >> x
        rows.append(b)
    print("  {%s}, /* U+%04X */" % (",".join("0x%02x" % r for r in rows), cp))
print("};")
