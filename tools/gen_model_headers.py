#!/usr/bin/env python3 -I
"""Generate src/engine/model/objects.hpp: one struct per recovered world class (layout observed in live objects).
usage: gen_model_headers.py work/class_model.json work/source_map.json work/class_edges.json work/classes.json out.hpp
Field names are `f_XX` unless a semantic name is registered below (confirmed by observation or by decompiled code)."""
import json, sys, collections, re
mj, sj, ej, cj, out = sys.argv[1:6]
model = json.load(open(mj)); smap = json.load(open(sj)); edges = json.load(open(ej)); cl = json.load(open(cj))
base = {k: max(v, key=v.get) for k, v in edges.items()}
# Semantics confirmed on units (VisibleThing family, 176 byte pool objects): offset -> (name, c type, comment)
KNOWN = {
    0x24: ('pos_x', 'int32_t', 'world pixel x (centre of the object)'),
    0x28: ('pos_y', 'int32_t', 'world pixel y'),
    0x30: ('anim_set', 'uint32_t', 'pointer to the animation set (guest address)'),
    0x38: ('hp', 'int32_t', 'current value (e.g. 0x1770), probably health'),
    0x44: ('tile_x', 'int32_t', 'map tile x (tile = 48 px)'),
    0x48: ('tile_y', 'int32_t', 'map tile y'),
    0x3c: ('hp_max', 'int32_t', 'per-type maximum health (footman 6000, rifleman 5000, archer 3500, knight 10000, bear 36000 ...)'),
    0x50: ('type_id', 'int32_t', 'object type = index into UGI_* (0..89)'),
    0x68: ('type_desc', 'uint32_t', 'pointer to the static per-type descriptor record (0x4c bytes, .data 0x4ac428+)'),
    0x5c: ('flags', 'uint32_t', 'state flags (e.g. 0x01000101)'),
    0x6c: ('fx_x', 'int32_t', 'fixed point x, pos_x * 256'),
    0x70: ('fx_y', 'int32_t', 'fixed point y, pos_y * 256'),
    0x74: ('target_x', 'int32_t', 'pixel x of the current step target'),
    0x78: ('target_y', 'int32_t', 'pixel y of the current step target'),
    0x80: ('dir_state', 'int32_t', 'direction / animation state (0..6)'),
    0x88: ('anim_tick', 'int32_t', 'animation counter'),
}
def name_of(vt):
    votes = smap['class_files'].get(vt) or []
    names = [f for f, n in votes if not f.startswith(('VisibleThing', 'ListTemplate', 'Data.'))]
    if names: return re.sub(r'\W', '_', names[0].rsplit('.', 1)[0])
    return 'Class_' + vt
def size_of(vt):
    s = model.get(vt, {}).get('sizes', {})
    nums = [int(k) for k in s if k.isdigit()]
    return max(nums, key=lambda k: s[str(k)]) if nums else None
L = ['// Generated by tools/gen_model_headers.py from live-object observation (15 campaign missions). Layout hypotheses, not ground truth.',
     '#pragma once', '#include <cstdint>', '', 'namespace aztec::model {', '']
seen_names = collections.Counter()
for vt in sorted(cl):
    m = model.get(vt)
    if not m or m['count'] == 0: continue
    sz = size_of(vt)
    if not sz or sz > 0x800 or sz % 4: continue
    nm = name_of(vt)
    seen_names[nm] += 1
    if seen_names[nm] > 1: nm += '_%s' % vt
    b = base.get(vt)
    L.append('// vtable %s, base vtable %s, %d virtual methods, %d live objects in %d missions' % (vt, b or '-', m['methods'], m['count'], len(m['missions'])))
    L.append('struct %s {' % nm)
    L.append('  uint32_t vtable;   // +0x00')
    off = 4
    flds = {f['off']: f for f in m['fields']}
    while off < sz:
        f = flds.get(off)
        if off in KNOWN and sz >= 0xb0:
            n, t, c = KNOWN[off]
            L.append('  %s %s;   // +0x%02x %s' % (t, n, off, c))
        elif f is None or f['kind'] == 'zero':
            # run of zero dwords
            run = 1
            while off + 4 * run < sz and (flds.get(off + 4 * run) is None or flds[off + 4 * run]['kind'] == 'zero') and (off + 4 * run) not in KNOWN: run += 1
            L.append('  uint32_t f_%02x[%d];   // +0x%02x (always 0 in survey)' % (off, run, off) if run > 1 else '  uint32_t f_%02x;   // +0x%02x (always 0 in survey)' % (off, off))
            off += 4 * run; continue
        else:
            ty = {'ptr': 'uint32_t', 'code/data ptr': 'uint32_t', 'int': 'int32_t'}.get(f['kind'], 'uint32_t')
            L.append('  %s f_%02x;   // +0x%02x %s, %d distinct values [%#x..%#x]' % (ty, off, off, f['kind'], f['distinct'], f['min'], f['max']))
        off += 4
    L.append('};')
    L.append('static_assert(sizeof(%s) == %d);' % (nm, sz))
    L.append('')
L.append('}  // namespace aztec::model')
import os
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write('\n'.join(L))
print('structs:', sum(1 for l in L if l.startswith('struct ')))
